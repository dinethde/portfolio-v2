#!/usr/bin/env python3
"""Turn the Figma variables export into Tailwind theme variables.

    python3 scripts/build_tokens.py            write src/styles/design-tokens.css
    python3 scripts/build_tokens.py --check    exit 1 if that file is out of date (CI)

Input is ``src/styles/figma-variables.json``, made by ``scripts/figma/export-variables.js``
through the Figma MCP. The output is generated: never edit it by hand.

Naming (TECH_SPEC §2.1):

    neutral/1100                    -> --color-neutral-1100            bg-neutral-1100
    bg/surface/page/active          -> --color-surface-page-active     bg-surface-page-active
    text/neutral/p1/active          -> --color-txt-neutral-p1-active   text-txt-neutral-p1-active
    components/pill/modern/border   -> --color-pill-modern-border      border-pill-modern-border
    radius/8                        -> --radius-8                      rounded-8
    space/16                        -> --spacing: 1px                  p-16, gap-16
    p/text/p2/500                   -> --text-p2 (+ line height)       text-p2 font-rounded font-medium
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path("src/styles/figma-variables.json")
OUTPUT = Path("src/styles/design-tokens.css")
PALETTE_COLLECTION = "color palate"  # sic: the collection's name in Figma
SEMANTIC_COLLECTION = "Portfolio / Color variables"


@dataclass(frozen=True)
class Font:
    """A Figma font family as a Tailwind ``--font-*`` theme value."""

    key: str
    stack: str

    @property
    def is_linked(self) -> bool:
        """True when the stack points at a CSS variable set outside :root (next/font)."""
        return "var(" in self.stack


FONTS = {
    "Instrument Serif": Font("serif", 'var(--font-instrument-serif, "Instrument Serif"), ui-serif, Georgia, serif'),
    "SF Pro": Font("sans", '-apple-system, BlinkMacSystemFont, "SF Pro Text", "SF Pro", system-ui, sans-serif'),
    "SF Compact Rounded": Font("rounded", 'ui-rounded, "SF Compact Rounded", "SF Pro Rounded", system-ui, sans-serif'),
}
# Figma text style (first three path parts) -> --text-<key>
TEXT_KEYS = {
    "p/title/one": "title-one",
    "p/title/accent": "title-accent",
    "p/heading/h1": "h1",
    "p/heading/h2": "h2",
    "p/text/p1": "p1",
    "p/text/p2": "p2",
    "p/text/p3": "p3",
}
# Theme values that aren't Figma variables (DESIGN.md: Layout, Elevation, Motion). They live in the
# generated file so it stays the only file with raw values (STATE.md D-10).
EXTRA = (
    "  /* ── Not stored as Figma variables (DESIGN.md: Layout, Elevation, Motion) ── */",
    "  --breakpoint-*: initial;",
    "  --breakpoint-tablet: 37.5rem; /* 600px  -> tablet: */",
    "  --breakpoint-desktop: 68.75rem; /* 1100px -> desktop: */",
    "  --shadow-pill: 0 0 1px rgb(0 0 0 / 0.08);",
    "  --shadow-card: 0 1px 2px rgb(0 0 0 / 0.12);",
    "  --ease-soft: cubic-bezier(0.22, 1, 0.36, 1);",
)
HEADER = (
    "/* Do not edit this file. It is generated from Figma by scripts/build_tokens.py.",
    " * Source: src/styles/figma-variables.json (Figma file op5jPr3yqBUUTyi2CJGQI3).",
    " * Change a value in Figma, re-export, then run: python3 scripts/build_tokens.py",
    " *",
    ' * Imported by src/app/globals.css right after @import "tailwindcss".',
    " * Every variable here becomes a :root CSS variable and a Tailwind utility.",
    " * The Tailwind defaults for colour, font size, radius and breakpoints are cleared, so only these values exist.",
    " * This is the only file in the repo allowed to hold raw colour values (scripts/check_tokens.py).",
    " */",
)


class TokenError(Exception):
    """The Figma export can't be turned into tokens."""


def color_var(name: str) -> str:
    """The CSS variable for a Figma colour path."""
    parts = name.split("/")
    if parts[0] in ("bg", "components"):
        parts = parts[1:]
    elif parts[0] == "text":
        parts = ["txt", *parts[1:]]
    return "--color-" + "-".join(parts)


def number(value: float) -> str:
    """A number without a trailing ``.0``."""
    return f"{value:g}"


def _colors(variables: list[dict[str, Any]]) -> list[str]:
    by_name = {v["name"]: v for v in variables}
    lines = ["  /* ── Colour primitives (Figma: color palate) ───────────────────────── */"]
    lines += [f"  {color_var(v['name'])}: {v['value']};" for v in variables if v["collection"] == PALETTE_COLLECTION]
    lines += ["", "  /* ── Semantic and component colours (Figma: Portfolio / Color variables) ── */"]
    group = None
    for v in (v for v in variables if v["collection"] == SEMANTIC_COLLECTION):
        alias = v.get("alias")
        if alias is not None and alias not in by_name:
            raise TokenError(f"{v['name']} points to {alias}, which isn't in the export")
        current = "/".join(v["name"].split("/")[:2])
        if current != group:
            lines.append(f"  /* {current} */")
            group = current
        value = f"var({color_var(alias)})" if alias is not None else v["value"]
        lines.append(f"  {color_var(v['name'])}: {value};")
    return lines


def _type_scale(text_styles: list[dict[str, Any]]) -> list[str]:
    lines = [
        "  /* ── Type (Figma text styles). Pair with a family and a weight:",
        "     p/text/p2/500 -> text-p2 font-rounded font-medium",
        "     normal -> font-normal (400) · 500 -> font-medium · 600 -> font-semibold */",
    ]
    seen: set[str] = set()
    for style in text_styles:
        base = "/".join(style["name"].split("/")[:3])
        key = TEXT_KEYS.get(base)
        if key is None:
            raise TokenError(f"no --text key for text style {style['name']}: add it to TEXT_KEYS")
        if style["family"] not in FONTS:
            raise TokenError(f"unknown font family {style['family']}: add it to FONTS")
        if key in seen:
            continue
        seen.add(key)
        family = FONTS[style["family"]]
        lines.append(f"  --text-{key}: {number(style['size'])}px; /* {style['family']} -> font-{family.key} */")
        lines.append(f"  --text-{key}--line-height: {number(round(style['lineHeightPercent'] / 100, 3))};")
        if style["letterSpacingPx"]:
            lines.append(f"  --text-{key}--letter-spacing: {number(style['letterSpacingPx'])}px;")
    return lines


def build(data: dict[str, Any]) -> str:
    """The whole token CSS file for a Figma export."""
    variables: list[dict[str, Any]] = data["variables"]
    text_styles: list[dict[str, Any]] = data["textStyles"]
    space = sorted({int(v["value"]) for v in variables if v["name"].startswith("space/")})
    radii = sorted((v for v in variables if v["name"].startswith("radius/")), key=lambda v: v["value"])
    borders = sorted({v["value"] for v in variables if v["name"].startswith("border/")})
    families = [FONTS[f] for f in dict.fromkeys(s["family"] for s in text_styles)]

    lines = [
        *HEADER,
        "",
        "@theme {",
        "  /* Clear Tailwind's defaults: only the Figma design system is available. */",
        "  --color-*: initial;",
        "  --text-*: initial;",
        "  --radius-*: initial;",
        "",
        "  /* ── Spacing ─────────────────────────────────────────────────────────",
        "     One Tailwind unit = 1px, so utilities read like the Figma names:",
        "     space/16 -> p-16, gap-16, mt-16 ... and widths too (w-600, max-w-750).",
        f"     Figma spacing scale: {', '.join(map(str, space))}. Stick to it. */",
        "  --spacing: 1px;",
        "",
        *_colors(variables),
        "",
        "  /* ── Radius (Figma: radius/*) ─────────────────────────────────────── */",
        *(f"  --radius-{number(v['value'])}: {number(v['value'])}px;" for v in radii),
        "",
        *_type_scale(text_styles),
        "",
        "  /* Border widths in Figma: " + ", ".join(number(b) + "px" for b in borders) + ".",
        "     Tailwind already maps these: border (1px), border-2, border-4, border-[1.5px], border-[7px]. */",
        "",
        "  /* ── Font families (Figma text styles) ── */",
        *(f"  --font-{f.key}: {f.stack};" for f in families if not f.is_linked),
        "",
        *EXTRA,
        "}",
    ]
    linked = [f for f in families if f.is_linked]
    if linked:
        lines += [
            "",
            "/* These families point at the next/font variable, which Next.js sets on <html>, not :root.",
            '   So they use `inline` (Tailwind docs: "Referencing other variables"). */',
            "@theme inline {",
            *(f"  --font-{f.key}: {f.stack};" for f in linked),
            "}",
        ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Write or check the token file. Returns the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the token file is out of date")
    args = parser.parse_args(argv)
    try:
        data = json.loads((ROOT / SOURCE).read_text(encoding="utf-8"))
        css = build(data)
    except (OSError, ValueError, KeyError, TokenError) as exc:
        print(f"build_tokens: {exc}", file=sys.stderr)
        return 2
    output = ROOT / OUTPUT
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != css:
            print(f"{OUTPUT} is out of date. Run: python3 scripts/build_tokens.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date")
        return 0
    output.write_text(css, encoding="utf-8")
    colours = sum(1 for v in data["variables"] if v["type"] == "COLOR")
    print(f"wrote {OUTPUT}: {colours} colours, {len(data['textStyles'])} text styles")
    return 0


if __name__ == "__main__":
    sys.exit(main())
